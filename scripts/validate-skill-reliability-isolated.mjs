import { withIsolatedDevelopment, waitForFact, requireFact } from './lib/isolated-development.mjs';

await withIsolatedDevelopment('skill-reliability', async ({ command, startBot, report }) => {
  await command('setblock 10 81 8 minecraft:barrel');
  const a = await startBot('SkillDevA');
  const scope = { serverProfileId: a.profile.id, dimension: 'minecraft:overworld' };
  const container = { x: 10, y: 81, z: 8 };
  await command(`tp ${a.id} 8.5 81 8.5`);
  await command(`give ${a.id} minecraft:cobblestone 4`);
  await waitForFact(() => a.count('cobblestone') === 4 && a.bot.blockAt(a.bot.entity.position.offset(2, 0, 0).floored())?.name === 'barrel', 'STORAGE_FIXTURE_UNCONFIRMED');
  const route = { ...scope, container, itemName: 'cobblestone', count: 8 };
  const partial = await a.invoke('store.sort', { routes: [route], startIndex: 0, maxTransfers: 1 });
  requireFact(partial.result.payload.outcome === 'completed' && partial.output.nextIndex === 0 && partial.output.remainingCount === 4 && !partial.output.completed, 'PARTIAL_SORT_FALSE_SUCCESS');
  requireFact((await command('execute if items block 10 81 8 container.* minecraft:cobblestone', false)).includes('Test passed'), 'DEPOSIT_SERVER_READBACK_FAILED');
  const duplicate = await a.invoke('store.sort', {}, { invocation: partial.invocation });
  requireFact(JSON.stringify(duplicate.result) === JSON.stringify(partial.result), 'DUPLICATE_RECEIPT_CHANGED');
  await command(`give ${a.id} minecraft:cobblestone 4`);
  await waitForFact(() => a.count('cobblestone') === 4, 'RESUME_MATERIALS_UNCONFIRMED');
  const resumed = await a.invoke('store.sort', { routes: [route], startIndex: 0, remainingCount: partial.output.remainingCount, maxTransfers: 1 });
  requireFact(resumed.output?.completed && resumed.output.nextIndex === 1 && a.count('cobblestone') === 0, 'SORT_RESUME_FAILED');
  report.checks.push('server-confirmed partial delivery, duplicate invocation and residual-only resume');
  const wrongBox = await a.invoke('pack.shulker', { ...scope, shulker: container, items: [{ itemName: 'cobblestone', count: 1 }], startIndex: 0, maxTransfers: 1 });
  requireFact(wrongBox.result.payload.errorCode === 'SHULKER_REQUIRED', 'WRONG_CONTAINER_ACCEPTED');
  report.checks.push('pack.shulker rejects a barrel');
  const b = await startBot('SkillDevB');
  await command(`tp ${b.id} 10.5 81 6.5`);
  await waitForFact(() => b.bot.entity.position.distanceTo(a.bot.entity.position) < 5, 'BOT_B_POSITION_UNCONFIRMED');
  const input = { ...scope, container, itemName: 'cobblestone', count: 6, direction: 'withdraw' };
  const results = await Promise.all([a.invoke('container.transfer', input), b.invoke('container.transfer', input)]);
  requireFact(results.every((r) => r.result.payload.outcome === 'completed' || r.result.payload.errorCode === 'WORKSTATION_BUSY'), 'CONCURRENT_TRANSFER_UNEXPECTED_FAILURE');
  const receipts = results.filter((r) => r.result.payload.outcome === 'completed');
  requireFact(receipts.every((r) => r.output.verification), 'UNVERIFIED_DELIVERY');
  const moved = receipts.reduce((n, r) => n + r.output.movedCount, 0);
  requireFact(moved <= 8 && moved === a.count('cobblestone') + b.count('cobblestone'), 'TWO_BOT_STOCK_NOT_CONSERVED');
  report.checks.push('two-Bot container contention and conserved receipts');
  await command(`clear ${a.id}`);
  await waitForFact(() => a.count('bread') === 0 && a.count('cobblestone') === 0, 'CLEAR_UNCONFIRMED');
  await command('summon minecraft:item 7.5 81 8.5 {Item:{id:"minecraft:bread",count:64},PickupDelay:20s}');
  const food = await a.invoke('food.secure', { ...scope, targetCount: 16 });
  requireFact(food.result.payload.outcome === 'completed' && food.output.targetReached && food.output.secured === 64 && a.count('bread') === 64, 'LARGE_FOOD_PICKUP_UNCONFIRMED');
  report.checks.push('food.secure confirms a 64-item pickup with a target of 16');
});
process.exit(process.exitCode ?? 0);
